-- Empty-project baseline for the tables that predate the versioned migrations.
-- Run this only for a new Supabase project. Existing projects already contain
-- these tables; CREATE TABLE IF NOT EXISTS keeps the migration non-destructive.

create extension if not exists pgcrypto;

create table if not exists public.books (
    id bigint generated by default as identity primary key,
    title text not null,
    author text,
    intro text not null,
    sample text not null,
    full_content text,
    status text not null default 'active',
    source_type text not null default 'demo_seed',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    cover_image_url text,
    cover_photographer text not null default '',
    cover_caption text not null default '',
    editor_feedback text not null default '',
    reviewed_at timestamptz,
    author_access_token_hash text not null,
    current_revision_no integer not null default 1,
    review_claimed_by uuid references auth.users(id) on delete set null,
    review_claimed_at timestamptz,
    review_claim_expires_at timestamptz
);

create table if not exists public.book_ai_tags (
    id bigint generated by default as identity primary key,
    book_id bigint not null references public.books(id) on delete cascade,
    setting_tags jsonb not null default '[]'::jsonb,
    story_tone_tags jsonb not null default '[]'::jsonb,
    relationship_core_tags jsonb not null default '[]'::jsonb,
    aesthetic_tags jsonb not null default '[]'::jsonb,
    risk_tags jsonb not null default '[]'::jsonb,
    recommend_reason text,
    tag_source text not null default 'manual',
    tag_status text not null default 'draft',
    llm_provider text,
    model_name text,
    prompt_version text,
    raw_response jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint book_ai_tags_book_id_key unique (book_id),
    constraint book_ai_tags_setting_array check (jsonb_typeof(setting_tags) = 'array'),
    constraint book_ai_tags_story_tone_array check (jsonb_typeof(story_tone_tags) = 'array'),
    constraint book_ai_tags_relationship_array check (jsonb_typeof(relationship_core_tags) = 'array'),
    constraint book_ai_tags_aesthetic_array check (jsonb_typeof(aesthetic_tags) = 'array'),
    constraint book_ai_tags_risk_array check (jsonb_typeof(risk_tags) = 'array')
);

create table if not exists public.feedbacks (
    id uuid primary key default gen_random_uuid(),
    request_id text,
    book_id bigint references public.books(id) on delete set null,
    book_title text not null,
    reason text not null,
    user_prefs jsonb not null default '{}'::jsonb,
    feedback_note text,
    created_at timestamptz not null default now(),
    reader_user_id uuid references auth.users(id) on delete cascade
);

create table if not exists public.recommendation_logs (
    id uuid primary key default gen_random_uuid(),
    request_id text not null,
    user_prefs jsonb not null default '{}'::jsonb,
    strategy_version text not null default 'v1',
    result_book_ids jsonb not null default '[]'::jsonb,
    result_scores jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now(),
    reader_user_id uuid references auth.users(id) on delete cascade
);

create table if not exists public.prompt_versions (
    id bigint generated by default as identity primary key,
    version text not null unique,
    name text not null,
    prompt_text text not null,
    output_schema jsonb not null default '{}'::jsonb,
    notes text,
    is_active boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.recommendation_strategies (
    id bigint generated by default as identity primary key,
    version text not null unique,
    name text not null,
    setting_weight numeric not null default 25,
    story_tone_weight numeric not null default 40,
    relationship_core_weight numeric not null default 35,
    max_score numeric not null default 96,
    notes text,
    is_active boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.system_configs (
    id bigint generated by default as identity primary key,
    config_key text not null unique,
    config_value text,
    config_desc text,
    is_active boolean not null default true,
    updated_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);

create table if not exists public.tag_vocabularies (
    id bigint generated by default as identity primary key,
    tag_type text not null,
    tag_name text not null,
    tag_desc text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    constraint tag_vocabularies_type_name_key unique (tag_type, tag_name)
);

alter table public.books enable row level security;
alter table public.book_ai_tags enable row level security;
alter table public.feedbacks enable row level security;
alter table public.recommendation_logs enable row level security;
alter table public.prompt_versions enable row level security;
alter table public.recommendation_strategies enable row level security;
alter table public.system_configs enable row level security;
alter table public.tag_vocabularies enable row level security;

revoke all on public.books from public, anon, authenticated;
revoke all on public.book_ai_tags from public, anon, authenticated;
revoke all on public.feedbacks from public, anon, authenticated;
revoke all on public.recommendation_logs from public, anon, authenticated;
revoke all on public.prompt_versions from public, anon, authenticated;
revoke all on public.recommendation_strategies from public, anon, authenticated;
revoke all on public.system_configs from public, anon, authenticated;
revoke all on public.tag_vocabularies from public, anon, authenticated;

grant all on public.books to service_role;
grant all on public.book_ai_tags to service_role;
grant all on public.feedbacks to service_role;
grant all on public.recommendation_logs to service_role;
grant all on public.prompt_versions to service_role;
grant all on public.recommendation_strategies to service_role;
grant all on public.system_configs to service_role;
grant all on public.tag_vocabularies to service_role;

grant usage, select on all sequences in schema public to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('covers', 'covers', true, 5242880, array['image/jpeg'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
